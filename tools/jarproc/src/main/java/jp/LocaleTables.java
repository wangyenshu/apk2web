package jp;

import java.io.IOException;
import java.nio.file.*;
import java.util.*;

/**
 * Writes runtime/framework/a2w/LocaleData.java: the ISO 639 languages and ISO 3166 countries with their three-letter
 * codes, and the ISO 3166-3 former countries, from the JDK this runs on (TeaVM's java.util.Locale lacks
 * getISOLanguages, getISOCountries and getISO3Language/Country). Usage (tools/localedata.sh):
 * java -cp jarproc.jar jp.LocaleTables OUT_DIR
 */
public class LocaleTables {
  @SuppressWarnings("deprecation")
  public static void main(String[] a) throws IOException {
    StringBuilder l = new StringBuilder(), c = new StringBuilder();
    for (String s : Locale.getISOLanguages()) l.append(l.length() > 0 ? "," : "").append(s).append('=').append(new Locale(s).getISO3Language());
    for (String s : Locale.getISOCountries()) c.append(c.length() > 0 ? "," : "").append(s).append('=').append(new Locale("", s).getISO3Country());
    String part3 = String.join(",", new TreeSet<>(Locale.getISOCountries(Locale.IsoCountryCode.PART3)));
    String src = "// Generated by tools/localedata.sh (jp.LocaleTables) from the tables of JDK " + System.getProperty("java.version") + ". Do not edit.\n"
        + "package a2w;\n\n"
        + "/** ISO 639 languages and ISO 3166 countries with their alpha-3 codes, and the ISO 3166-3 former countries. */\n"
        + "public final class LocaleData {\n"
        + "  private LocaleData() {}\n"
        + "  /** language=alpha3 pairs, comma separated, sorted */\n"
        + "  public static final String LANGUAGES = \"" + l + "\";\n"
        + "  /** country=alpha3 pairs, comma separated, sorted */\n"
        + "  public static final String COUNTRIES = \"" + c + "\";\n"
        + "  /** ISO 3166-3 codes of former countries */\n"
        + "  public static final String PART3 = \"" + part3 + "\";\n"
        + "  private static java.util.Map<String, String> languages, countries;\n"
        + "  static java.util.Map<String, String> map(String pairs) {\n"
        + "    java.util.Map<String, String> m = new java.util.LinkedHashMap<>();\n"
        + "    for (String p : pairs.split(\",\")) { int e = p.indexOf('='); m.put(p.substring(0, e), p.substring(e + 1)); }\n"
        + "    return m;\n"
        + "  }\n"
        + "  public static java.util.Map<String, String> languages() { if (languages == null) languages = map(LANGUAGES); return languages; }\n"
        + "  public static java.util.Map<String, String> countries() { if (countries == null) countries = map(COUNTRIES); return countries; }\n"
        + "}\n";
    Path p = Paths.get(a[0], "a2w", "LocaleData.java");
    Files.createDirectories(p.getParent());
    Files.writeString(p, src);
  }
}
