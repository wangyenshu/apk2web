package jp;

import java.io.IOException;
import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.nio.file.*;
import java.util.*;

/**
 * Writes the Unicode block and script tables of java.lang.Character.UnicodeBlock and UnicodeScript (and ICU's
 * UCharacter.UnicodeBlock ranges) from the JDK this runs on, which TeaVM's class library lacks:
 * runtime/framework/a2w/UnicodeData.java. Usage (tools/unicode.sh):
 * java --add-opens java.base/java.lang=ALL-UNNAMED -cp jarproc.jar jp.UnicodeTables OUT_DIR
 */
public class UnicodeTables {
  public static void main(String[] a) throws Exception {
    Path out = Paths.get(a[0]);
    // blocks: every public static UnicodeBlock field, in declaration order
    List<String> blocks = new ArrayList<>();
    Map<Character.UnicodeBlock, Integer> blockIndex = new IdentityHashMap<>();
    for (Field f : Character.UnicodeBlock.class.getFields())
      if (Modifier.isStatic(f.getModifiers()) && f.getType() == Character.UnicodeBlock.class) {
        Character.UnicodeBlock b = (Character.UnicodeBlock) f.get(null);
        if (blockIndex.containsKey(b)) continue;   // deprecated aliases (SURROGATES_AREA ...) are other objects
        blockIndex.put(b, blocks.size());
        blocks.add(f.getName());
      }
    // block ranges: start code point and block index (-1: none)
    List<int[]> br = runs(cp -> { Character.UnicodeBlock b = Character.UnicodeBlock.of(cp); return b == null ? -1 : blockIndex.get(b); });
    List<int[]> sr = runs(cp -> Character.UnicodeScript.of(cp).ordinal());
    // forName aliases: the JDK's own lookup map (canonical names, names with spaces, without spaces)
    Field mf = Character.UnicodeBlock.class.getDeclaredField("map");
    mf.setAccessible(true);
    @SuppressWarnings("unchecked") Map<String, Character.UnicodeBlock> map = (Map<String, Character.UnicodeBlock>) mf.get(null);
    TreeMap<String, Integer> aliases = new TreeMap<>();
    for (Map.Entry<String, Character.UnicodeBlock> e : map.entrySet()) {
      Integer i = blockIndex.get(e.getValue());
      if (i != null && !e.getKey().equals(blocks.get(i))) aliases.put(e.getKey(), i);
    }
    StringBuilder b = new StringBuilder();
    b.append("package a2w;\n\n");
    b.append("/** Unicode block and script ranges (the Unicode version ").append(unicodeVersion()).append("; generated by tools/unicode.sh). */\n");
    b.append("public final class UnicodeData {\n  private UnicodeData() {}\n");
    b.append("  /** java.lang.Character.UnicodeBlock names, by index */\n");
    b.append("  public static final String[] BLOCKS = {\n").append(strings(blocks)).append("  };\n");
    b.append("  /** other names Character.UnicodeBlock.forName accepts (upper case), and the block's index */\n");
    b.append("  public static final String[] ALIASES = {\n").append(strings(new ArrayList<>(aliases.keySet()))).append("  };\n");
    b.append("  public static final int[] ALIAS_BLOCKS = ").append(chunked(ints(new ArrayList<>(aliases.values())))).append(";\n");
    b.append("  /** where each run of code points with the same block starts, and the block's index (-1: none) */\n");
    b.append("  public static final int[] BLOCK_STARTS = ").append(chunked(col(br, 0))).append(";\n");
    b.append("  public static final int[] BLOCK_OF = ").append(chunked(col(br, 1))).append(";\n");
    b.append("  /** where each run of code points with the same script starts, and the script's ordinal in Character.UnicodeScript */\n");
    b.append("  public static final String SCRIPTS = \"").append(packed(sr)).append("\";\n");
    b.append("  /** Character.UnicodeScript names, by ordinal */\n");
    List<String> sn = new ArrayList<>();
    for (Character.UnicodeScript s : Character.UnicodeScript.values()) sn.add(s.name());
    b.append("  public static final String[] SCRIPT_NAMES = {\n").append(strings(sn)).append("  };\n");
    b.append("  /** script aliases (ISO 15924 codes, upper case) and their script ordinals */\n");
    List<String> codes = new ArrayList<>(); List<Integer> codeOf = new ArrayList<>();
    for (Character.UnicodeScript s : Character.UnicodeScript.values()) {
      for (String code : scriptCodes(s)) { codes.add(code); codeOf.add(s.ordinal()); }
    }
    b.append("  public static final String[] SCRIPT_CODES = {\n").append(strings(codes)).append("  };\n");
    b.append("  public static final int[] SCRIPT_CODE_OF = ").append(chunked(ints(codeOf))).append(";\n");
    // Character.getDirectionality runs, and binary properties TeaVM's Character lacks
    b.append("  /** where each run of code points with the same bidirectional class starts, and the class (Character.DIRECTIONALITY_*, 0xff: undefined) */\n");
    b.append("  public static final String DIRECTIONALITY = \"").append(packed(runs(cp -> Character.getDirectionality(cp) & 0xff))).append("\";\n");
    String[][] props = {{"MIRRORED", "isMirrored"}, {"IDEOGRAPHIC", "isIdeographic"}, {"EMOJI", "isEmoji"}, {"EMOJI_PRESENTATION", "isEmojiPresentation"},
        {"EMOJI_MODIFIER", "isEmojiModifier"}, {"EMOJI_MODIFIER_BASE", "isEmojiModifierBase"}, {"EMOJI_COMPONENT", "isEmojiComponent"},
        {"EXTENDED_PICTOGRAPHIC", "isExtendedPictographic"}};
    for (String[] pr : props) {
      java.lang.reflect.Method pm = Character.class.getMethod(pr[1], int.class);
      b.append("  /** Character.").append(pr[1]).append(": runs (start, 1 in / 0 out) */\n");
      b.append("  public static final String ").append(pr[0]).append(" = \"").append(packed(runs(cp -> { try { return (Boolean) pm.invoke(null, cp) ? 1 : 0; } catch (Exception e) { throw new RuntimeException(e); } }))).append("\";\n");
    }
    b.append("  /** the value of a run table (packed: start high, start low, value) at cp */\n");
    b.append("  public static int lookup(String runs, int cp) { int lo = 0, hi = runs.length() / 3 - 1; while (lo < hi) { int m = (lo + hi + 1) >>> 1; if ((runs.charAt(3 * m) << 16 | runs.charAt(3 * m + 1)) <= cp) lo = m; else hi = m - 1; } return runs.charAt(3 * lo + 2); }\n");
    b.append("  /** the index in BLOCK_STARTS of the run containing cp */\n");
    b.append("  public static int blockRun(int cp) { int lo = 0, hi = BLOCK_STARTS.length - 1; while (lo < hi) { int m = (lo + hi + 1) >>> 1; if (BLOCK_STARTS[m] <= cp) lo = m; else hi = m - 1; } return lo; }\n");
    b.append("  private static int[] scriptStarts, scriptOf;\n");
    b.append("  /** the script ordinal of cp */\n");
    b.append("  public static int script(int cp) {\n");
    b.append("    if (scriptStarts == null) { int n = SCRIPTS.length() / 3; int[] s = new int[n], o = new int[n]; for (int i = 0; i < n; i++) { s[i] = SCRIPTS.charAt(3 * i) << 16 | SCRIPTS.charAt(3 * i + 1); o[i] = SCRIPTS.charAt(3 * i + 2); } scriptOf = o; scriptStarts = s; }\n");
    b.append("    int lo = 0, hi = scriptStarts.length - 1; while (lo < hi) { int m = (lo + hi + 1) >>> 1; if (scriptStarts[m] <= cp) lo = m; else hi = m - 1; } return scriptOf[lo];\n  }\n");
    b.append("}\n");
    Files.createDirectories(out.resolve("a2w"));
    Files.writeString(out.resolve("a2w/UnicodeData.java"), b.toString());
    System.out.println(blocks.size() + " blocks, " + br.size() + " block runs, " + sr.size() + " script runs, " + aliases.size() + " aliases");
  }

  interface F { int of(int cp); }
  static List<int[]> runs(F f) {
    List<int[]> r = new ArrayList<>();
    int prev = Integer.MIN_VALUE;
    for (int cp = 0; cp <= Character.MAX_CODE_POINT; cp++) {
      int v = f.of(cp);
      if (v != prev) { r.add(new int[]{cp, v}); prev = v; }
    }
    return r;
  }
  static List<Integer> col(List<int[]> r, int i) { List<Integer> l = new ArrayList<>(); for (int[] x : r) l.add(x[i]); return l; }
  static List<Integer> ints(List<Integer> l) { return l; }
  static String chunked(List<Integer> l) {
    StringBuilder b = new StringBuilder("{");
    for (int i = 0; i < l.size(); i++) { b.append(i % 16 == 0 ? "\n    " : " ").append(l.get(i)).append(i < l.size() - 1 ? "," : ""); }
    return b.append("\n  }").toString();
  }
  static String strings(List<String> l) {
    StringBuilder b = new StringBuilder("    ");
    int col = 4;
    for (int i = 0; i < l.size(); i++) {
      String s = "\"" + l.get(i) + "\"" + (i < l.size() - 1 ? ", " : "");
      if (col + s.length() > 118) { b.append("\n    "); col = 4; }
      b.append(s); col += s.length();
    }
    return b.append('\n').toString();
  }
  /** three chars per run: start high, start low, value (Java string escapes) */
  static String packed(List<int[]> r) {
    StringBuilder b = new StringBuilder();
    for (int[] x : r) { esc(b, x[0] >>> 16); esc(b, x[0] & 0xffff); esc(b, x[1]); }
    return b.toString();
  }
  static void esc(StringBuilder b, int c) {
    // \\u escapes are read before the lexer: line terminators, quote and backslash need their own escapes
    switch (c) {
      case '\n': b.append("\\n"); break;
      case '\r': b.append("\\r"); break;
      case '"': b.append("\\\""); break;
      case '\\': b.append("\\\\"); break;
      default: b.append(String.format("\\u%04x", c));
    }
  }
  static String unicodeVersion() { return "of Java " + Runtime.version().feature(); }
  /** the ISO 15924 codes UnicodeScript.forName accepts for s (found by asking the JDK for every four-letter code) */
  static List<String> scriptCodes(Character.UnicodeScript s) {
    if (CODES == null) {
      CODES = new HashMap<>();
      char[] c = new char[4];
      for (c[0] = 'A'; c[0] <= 'Z'; c[0]++) for (c[1] = 'A'; c[1] <= 'Z'; c[1]++) for (c[2] = 'A'; c[2] <= 'Z'; c[2]++) for (c[3] = 'A'; c[3] <= 'Z'; c[3]++) {
        String code = new String(c);
        try { Character.UnicodeScript x = Character.UnicodeScript.forName(code); if (!x.name().equals(code)) CODES.computeIfAbsent(x, k -> new ArrayList<>()).add(code); } catch (IllegalArgumentException e) {}
      }
    }
    return CODES.getOrDefault(s, List.of());
  }
  static Map<Character.UnicodeScript, List<String>> CODES;
}
