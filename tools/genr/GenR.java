import java.lang.reflect.*;
import java.net.*;
import java.util.*;
public class GenR {
  public static void main(String[] a) throws Exception {
    URLClassLoader cl = new URLClassLoader(new URL[] {new java.io.File(a[0]).toURI().toURL()}, null);
    Class<?> r = cl.loadClass("android.R");
    StringBuilder sb = new StringBuilder();
    sb.append("package android;\n\n/** android.R: every public framework resource id of API ").append(a[1]).append(" (generated by tools/gen_android_r.sh from android.jar). */\npublic final class R {\n  public R() {}\n");
    Class<?>[] inner = r.getDeclaredClasses();
    Arrays.sort(inner, Comparator.comparing(Class::getSimpleName));
    for (Class<?> c : inner) {
      sb.append("  public static final class ").append(c.getSimpleName()).append(" {\n    public ").append(c.getSimpleName()).append("() {}\n");
      Field[] fs = c.getDeclaredFields();
      Arrays.sort(fs, Comparator.comparing(Field::getName));
      for (Field f : fs) {
        int m = f.getModifiers();
        if (!Modifier.isPublic(m) || !Modifier.isStatic(m)) continue;
        String dep = f.isAnnotationPresent(Deprecated.class) ? "@Deprecated " : "";
        if (f.getType() == int.class) sb.append("    ").append(dep).append("public static final int ").append(f.getName()).append(" = 0x").append(String.format("%08x", f.getInt(null))).append(";\n");
        else if (f.getType() == int[].class) {
          int[] v = (int[]) f.get(null);
          sb.append("    public static final int[] ").append(f.getName()).append(" = {");
          for (int i = 0; i < v.length; i++) sb.append(i == 0 ? "" : ", ").append(String.format("0x%08x", v[i]));
          sb.append("};\n");
        }
      }
      sb.append("  }\n");
    }
    sb.append("}\n");
    System.out.print(sb);
  }
}
