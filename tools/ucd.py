#!/usr/bin/env python3
"""Writes the Unicode tables TeaVM's class library lacks, from ICU's preparsed Unicode Character Database (ppucd.txt
of ICU release ICU_TAG) and its CaseFolding.txt:

  runtime/framework/a2w/CaseFolding.java  simple, full and Turkic case folding (UCharacter.foldCase)
  runtime/framework/a2w/UcdData.java      East Asian width, bidi mirroring glyphs and paired brackets, canonical
                                          combining classes, decompositions and composition exclusions
                                          (java.text.Normalizer), numeric values

Usage: tools/ucd.py (needs network access to GitHub).
"""
import os, urllib.request
from fractions import Fraction

ICU_TAG = 'release-74-2'
BASE = 'https://raw.githubusercontent.com/unicode-org/icu/%s/icu4c/source/data/unidata/' % ICU_TAG
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.environ.get('UCD_OUT') or os.path.join(ROOT, 'runtime', 'framework', 'a2w')
MAX = 0x110000


def get(name):
    return urllib.request.urlopen(BASE + name).read().decode('utf-8')


def rng(s):
    a, _, b = s.partition('..')
    return int(a, 16), int(b or a, 16) + 1


def parse_ppucd(text):
    """per property: value for every code point (defaults, then blocks, then code point lines)"""
    defaults, blocks, cps, unassigned = {}, [], [], []
    for line in text.splitlines():
        if not line or line.startswith('#'): continue
        f = line.split(';')
        kind = f[0]
        if kind not in ('defaults', 'block', 'cp', 'unassigned'): continue
        lo, hi = rng(f[1])
        props = {}
        for item in f[2:]:
            if not item: continue
            if '=' in item:
                k, v = item.split('=', 1)
                props[k] = v
            elif item.startswith('-'): props[item[1:]] = False
            else: props[item] = True
        if kind == 'defaults': defaults = props
        elif kind == 'block': blocks.append((lo, hi, props))
        elif kind == 'cp': cps.append((lo, hi, props))
        else: unassigned.append((lo, hi))
    return defaults, blocks, cps, unassigned


def values(prop, defaults, blocks, cps, unassigned, default=None):
    v = [defaults.get(prop, default)] * MAX
    for lo, hi, p in blocks:
        if prop in p: v[lo:hi] = [p[prop]] * (hi - lo)
    for lo, hi, p in cps:
        if prop in p: v[lo:hi] = [p[prop]] * (hi - lo)
    return v


def runs(vals):
    out, prev = [], object()
    for cp, x in enumerate(vals):
        if x != prev: out.append((cp, x)); prev = x
    return out


def esc_units(units):
    m = {0x0a: '\\n', 0x0d: '\\r', 0x22: '\\"', 0x5c: '\\\\'}
    return ''.join(m.get(u, '\\u%04x' % u) for u in units)


def packed_runs(rs):
    """three chars per run: start high, start low, value"""
    u = []
    for cp, x in rs: u += [cp >> 16, cp & 0xffff, x]
    return esc_units(u)


def utf16(cps):
    u = []
    for c in cps:
        if c >= 0x10000: c -= 0x10000; u += [0xD800 + (c >> 10), 0xDC00 + (c & 0x3FF)]
        else: u.append(c)
    return u


def chunks(s, n=2000):
    """a long string constant as concatenated literals (a constant must stay under 64 KiB of modified UTF-8)"""
    parts, i = [], 0
    while i < len(s):
        j = min(len(s), i + n)
        while j < len(s) and s[j - 1] == '\\': j -= 1   # do not split an escape
        # back up to the start of a \\uXXXX escape if j is inside one
        k = s.rfind('\\', max(i, j - 6), j)
        if k >= 0 and j < len(s) and k + 6 > j: j = k
        parts.append('"%s"' % s[i:j]); i = j
    return '\n      + '.join(parts) if parts else '""'


def main():
    pp = get('ppucd.txt')
    version = next(l for l in pp.splitlines() if l.startswith('ucd;')).split(';')[1]
    d, b, c, un = parse_ppucd(pp)
    java = ['package a2w;', '',
            '/** Unicode %s character properties (from ICU %s ppucd.txt): generated by tools/ucd.py. */' % (version, ICU_TAG),
            'public final class UcdData {', '  private UcdData() {}', '  public static final String UNICODE_VERSION = "%s";' % version]
    # East Asian width: AndroidCharacter / UCharacter.EastAsianWidth numbering
    EA = {'N': 0, 'A': 1, 'H': 2, 'F': 3, 'Na': 4, 'W': 5}
    ea = [EA[x] for x in values('ea', d, b, c, un)]
    java.append('  /** East Asian width runs (start high, start low, value: 0 N, 1 A, 2 H, 3 F, 4 Na, 5 W) */')
    java.append('  public static final String EAST_ASIAN_WIDTH = %s;' % chunks(packed_runs(runs(ea))))
    # canonical combining class
    ccc = [int(x) for x in values('ccc', d, b, c, un, '0')]
    java.append('  /** canonical combining class runs */')
    java.append('  public static final String COMBINING_CLASS = %s;' % chunks(packed_runs(runs(ccc))))
    # mirroring glyphs and paired brackets (sparse: sorted pairs)
    bmg, bpb, bpt = [], [], []
    for lo, hi, p in c:
        for cp in range(lo, hi):
            if 'bmg' in p and p['bmg'] not in ('<code point>', ''): bmg.append((cp, int(p['bmg'], 16)))
            if 'bpb' in p and p['bpb'] not in ('<code point>', '') and p.get('bpt', 'n') != 'n':
                bpb.append((cp, int(p['bpb'], 16), {'o': 1, 'c': 2}[p['bpt']]))
    # sparse tables as packed strings (large array initializers overflow a class initializer): code points as two chars
    def cp2(x): return [x >> 16, x & 0xffff]
    u = []
    for f, t in bmg: u += cp2(f) + cp2(t)
    java.append('  /** Bidi_Mirroring_Glyph: (code point, glyph) pairs, sorted, two chars each */')
    java.append('  public static final String MIRRORS = %s;' % chunks(esc_units(u)))
    u = []
    for f, t, ty in bpb: u += cp2(f) + cp2(t) + [ty]
    java.append('  /** paired brackets: (code point, pair, type 1 open / 2 close), sorted */')
    java.append('  public static final String BRACKETS = %s;' % chunks(esc_units(u)))
    dm = values('dm', d, b, c, un)
    dt = values('dt', d, b, c, un)
    compex = values('Comp_Ex', d, b, c, un, False)
    u, cex, n = [], [], 0
    for cp in range(MAX):
        if 0xAC00 <= cp <= 0xD7A3: continue
        m = dm[cp]
        if m and m != '<code point>' and dt[cp] != 'None':
            units = utf16([int(x, 16) for x in m.split()])
            u += cp2(cp) + [len(units) | (0 if dt[cp] == 'Can' else 0x100)] + units
            n += 1
        if compex[cp] is True: cex += cp2(cp)
    java.append('  /** decompositions, sorted: code point, length | 0x100 for a compatibility mapping, the mapping (UTF-16); Hangul syllables are algorithmic */')
    java.append('  public static final String DECOMPOSITIONS = %s;' % chunks(esc_units(u)))
    java.append('  /** Full_Composition_Exclusion code points, sorted */')
    java.append('  public static final String COMPOSITION_EXCLUSIONS = %s;' % chunks(esc_units(cex)))
    dfrom = [0] * n
    nv = values('nv', d, b, c, un)
    distinct = sorted({x for x in nv if x not in (None, 'NaN', '')}, key=lambda x: float(Fraction(x)))
    index = {x: i + 1 for i, x in enumerate(distinct)}
    nvr = runs([index.get(x, 0) for x in nv])
    java.append('  /** numeric values (index 0: none) */')
    java.append('  public static final double[] NUMERIC_VALUES = {Double.NaN, %s};' % ', '.join(repr(float(Fraction(x))) for x in distinct))
    java.append('  /** numeric value runs: (start, index in NUMERIC_VALUES) */')
    java.append('  public static final String NUMERIC = %s;' % chunks(packed_runs(nvr)))
    java.append('''
  /** the value of a run table (packed: start high, start low, value) at cp */
  public static int lookup(String runs, int cp) {
    int lo = 0, hi = runs.length() / 3 - 1;
    while (lo < hi) { int m = (lo + hi + 1) >>> 1; if ((runs.charAt(3 * m) << 16 | runs.charAt(3 * m + 1)) <= cp) lo = m; else hi = m - 1; }
    return runs.charAt(3 * lo + 2);
  }
  /** index of cp in a sorted table of records starting with a two-char code point, or -1 */
  private static int find(String table, int recordLength, int cp) {
    int lo = 0, hi = table.length() / recordLength - 1;
    while (lo <= hi) {
      int m = (lo + hi) >>> 1, at = m * recordLength, v = table.charAt(at) << 16 | table.charAt(at + 1);
      if (v == cp) return at;
      if (v < cp) lo = m + 1; else hi = m - 1;
    }
    return -1;
  }
  public static int eastAsianWidth(int cp) { return lookup(EAST_ASIAN_WIDTH, cp); }
  public static int combiningClass(int cp) { return cp < 0x300 ? 0 : lookup(COMBINING_CLASS, cp); }
  /** the Bidi_Mirroring_Glyph of cp, or cp */
  public static int mirror(int cp) { int i = find(MIRRORS, 4, cp); return i >= 0 ? MIRRORS.charAt(i + 2) << 16 | MIRRORS.charAt(i + 3) : cp; }
  /** the Bidi_Paired_Bracket of cp, or cp */
  public static int pairedBracket(int cp) { int i = find(BRACKETS, 5, cp); return i >= 0 ? BRACKETS.charAt(i + 2) << 16 | BRACKETS.charAt(i + 3) : cp; }
  /** 0 none, 1 open, 2 close */
  public static int pairedBracketType(int cp) { int i = find(BRACKETS, 5, cp); return i >= 0 ? BRACKETS.charAt(i + 4) : 0; }
  private static int[] decompIndex;   // code point -> offset of its record, sorted by code point
  private static int[] decompCps;
  /** the decomposition mapping of cp (not Hangul syllables), or null; compat: whether compatibility mappings count */
  public static String decomposition(int cp, boolean compat) {
    if (decompCps == null) {
      String t = DECOMPOSITIONS;
      int n = 0;
      for (int i = 0; i < t.length(); i += 3 + (t.charAt(i + 2) & 0xff)) n++;
      int[] cps = new int[n], at = new int[n];
      for (int i = 0, k = 0; i < t.length(); i += 3 + (t.charAt(i + 2) & 0xff), k++) { cps[k] = t.charAt(i) << 16 | t.charAt(i + 1); at[k] = i; }
      decompIndex = at;
      decompCps = cps;
    }
    int k = java.util.Arrays.binarySearch(decompCps, cp);
    if (k < 0) return null;
    int i = decompIndex[k], len = DECOMPOSITIONS.charAt(i + 2);
    if (!compat && (len & 0x100) != 0) return null;
    return DECOMPOSITIONS.substring(i + 3, i + 3 + (len & 0xff));
  }
  public static boolean compositionExcluded(int cp) { return find(COMPOSITION_EXCLUSIONS, 2, cp) >= 0; }
  /** the numeric value of cp, or NaN */
  public static double numericValue(int cp) { return NUMERIC_VALUES[lookup(NUMERIC, cp)]; }
}
''')
    open(os.path.join(OUT, 'UcdData.java'), 'w').write('\n'.join(java))
    print('UcdData: %d decompositions, %d mirrors, %d brackets, %d exclusions' % (len(dfrom), len(bmg), len(bpb), len(cex) // 2))

    # case folding
    text = get('CaseFolding.txt')
    cf_version = text.splitlines()[0].lstrip('# ').strip()
    simple, full = {}, {}
    for line in text.splitlines():
        line = line.split('#')[0].strip()
        if not line: continue
        code, status, mapping = [x.strip() for x in line.split(';')[:3]]
        cp, to = int(code, 16), [int(x, 16) for x in mapping.split()]
        if status in ('C', 'S'): simple[cp] = to[0]
        if status in ('C', 'F'): full[cp] = to
    keys = sorted(simple)
    fk = sorted(k for k in full if len(full[k]) > 1)
    java = ['package a2w;', '', '/** Unicode case folding (%s, from ICU %s): generated by tools/ucd.py. */' % (cf_version, ICU_TAG),
            'public final class CaseFolding {', '  private CaseFolding() {}',
            '  /** code points with a simple folding, sorted, and what they fold to */',
            '  private static final int[] SIMPLE_FROM = {%s};' % ', '.join(str(k) for k in keys),
            '  private static final int[] SIMPLE_TO = {%s};' % ', '.join(str(simple[k]) for k in keys),
            '  /** code points whose full folding is more than one code point, and that folding */',
            '  private static final int[] FULL_FROM = {%s};' % ', '.join(str(k) for k in fk),
            '  private static final String[] FULL_TO = {%s};' % ', '.join('"%s"' % esc_units(utf16(full[k])) for k in fk),
            '''  /** the simple case folding of cp; turkic: the Turkic mappings of I and dotted I */
  public static int simple(int cp, boolean turkic) {
    if (turkic) { if (cp == 0x49) return 0x131; if (cp == 0x130) return 0x69; }
    int i = java.util.Arrays.binarySearch(SIMPLE_FROM, cp);
    return i >= 0 ? SIMPLE_TO[i] : cp;
  }
  /** the full case folding of s */
  public static String full(String s, boolean turkic) {
    StringBuilder b = new StringBuilder(s.length());
    for (int i = 0; i < s.length(); ) {
      int cp = s.codePointAt(i);
      i += Character.charCount(cp);
      if (turkic && (cp == 0x49 || cp == 0x130)) { b.append(cp == 0x49 ? '\\u0131' : 'i'); continue; }
      int f = java.util.Arrays.binarySearch(FULL_FROM, cp);
      if (f >= 0) { b.append(FULL_TO[f]); continue; }
      b.appendCodePoint(simple(cp, false));
    }
    return b.toString();
  }
}
''']
    open(os.path.join(OUT, 'CaseFolding.java'), 'w').write('\n'.join(java))
    print('CaseFolding: %d simple, %d full' % (len(keys), len(fk)))


if __name__ == '__main__':
    main()
