#!/usr/bin/env python3
"""Extract the public framework resource ids (android.R.<type>.<name> = 0x01xxxxxx) from an android.jar into
runtime/res/fwids.txt. Apps compile these constants into their code, so the web framework needs the real id of every
framework resource to name it (layouts, strings, attrs, styles, drawables...). Framework ids never change between
API levels (public.xml keeps them stable), so one table from the newest SDK serves every app.

usage: gen_fwres.py <android.jar> [out]
"""
import os, struct, sys, zipfile


def constants(data):
    """static final int fields with a ConstantValue: [(name, value)]"""
    p = 10
    count = struct.unpack('>H', data[8:10])[0]
    pool = [None] * count
    i = 1
    while i < count:
        tag = data[p]
        if tag == 1:
            n = struct.unpack('>H', data[p + 1:p + 3])[0]
            pool[i] = ('utf8', data[p + 3:p + 3 + n].decode('utf-8', 'replace')); p += 3 + n
        elif tag == 3: pool[i] = ('int', struct.unpack('>i', data[p + 1:p + 5])[0]); p += 5
        elif tag == 4: p += 5
        elif tag in (5, 6): p += 9; i += 1
        elif tag in (7, 8, 16, 19, 20): p += 3
        elif tag in (9, 10, 11, 12, 17, 18): p += 5
        elif tag == 15: p += 4
        else: raise ValueError('constant pool tag %d' % tag)
        i += 1
    p += 6
    ifaces = struct.unpack('>H', data[p:p + 2])[0]; p += 2 + 2 * ifaces
    nfields = struct.unpack('>H', data[p:p + 2])[0]; p += 2
    out = []
    for _ in range(nfields):
        _flags, name_i, desc_i, nattr = struct.unpack('>HHHH', data[p:p + 8]); p += 8
        for _ in range(nattr):
            an, alen = struct.unpack('>HI', data[p:p + 6])
            if pool[an][1] == 'ConstantValue' and pool[desc_i][1] == 'I':
                v = pool[struct.unpack('>H', data[p + 6:p + 8])[0]]
                if v and v[0] == 'int': out.append((pool[name_i][1], v[1]))
            p += 6 + alen
    return out


def main():
    jar = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), '..', 'runtime', 'res', 'fwids.txt')
    rows = []
    with zipfile.ZipFile(jar) as z:
        for n in z.namelist():
            if not n.startswith('android/R$') or not n.endswith('.class'): continue
            t = n[len('android/R$'):-len('.class')]
            if t == 'styleable': continue
            for name, v in constants(z.read(n)):
                if (v >> 24) & 0xff != 0x01: continue
                # android.R names use '_' where resource names have '.' only for styles (Theme_Holo -> Theme.Holo)
                rows.append((v, t, name.replace('_', '.') if t == 'style' else name))
    rows.sort()
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, 'w') as f:
        f.write('# android.R ids from %s (generated by tools/gen_fwres.py)\n' % os.path.basename(os.path.dirname(jar)))
        for v, t, name in rows: f.write('%08x %s %s\n' % (v, t, name))
    print('gen_fwres: %d ids -> %s' % (len(rows), out))


if __name__ == '__main__':
    main()
