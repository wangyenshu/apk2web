#!/usr/bin/env python3
"""Writes runtime/framework/com/android/internal/R.java: the R class AOSP's framework sources use, for classes ported
with tools/aosp.py. styleable arrays come from AOSP's core/res/res/values/attrs.xml (pinned commit of tools/aosp.py);
attributes are android.R.attr ids from android.jar (a private attribute gets 0, so a TypedArray never finds it and
the code keeps its default). The other resource types are android.R's public ids.

Usage: tools/gen_internal_r.py ANDROID_JAR
"""
import os, re, subprocess, sys
import xml.etree.ElementTree as ET
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import aosp

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
jar = sys.argv[1]


def public_ids(kind):
    out = subprocess.run(['javap', '-constants', '-cp', jar, 'android.R$' + kind], capture_output=True, text=True).stdout
    return {m.group(1): int(m.group(2)) for m in re.finditer(r'public static final int (\w+) = (-?\d+);', out)}


attr_ids = public_ids('attr')
root = ET.fromstring(aosp.fetch('platform/frameworks/base', 'core/res/res/values/attrs.xml'))
styleables = []
for ds in root.iter('declare-styleable'):
    names = []
    for a in ds.findall('attr'):
        n = a.get('name')
        n = n[8:] if n.startswith('android:') else n
        if n not in names: names.append(n)
    styleables.append((ds.get('name'), names))
all_attrs = sorted({n for _, ns in styleables for n in ns} | set(attr_ids))
lines = ['package com.android.internal;', '',
         '/** Generated by tools/gen_internal_r.py: AOSP\'s internal R for ported framework sources (public ids; private ones are 0). */',
         'public final class R {', '  private R() {}']
lines.append('  public static final class attr {')
for n in all_attrs: lines.append('    public static final int %s = %d;' % (n, attr_ids.get(n, 0)))
lines.append('  }')
for kind in ('string', 'drawable', 'layout', 'dimen', 'color', 'style', 'id', 'integer', 'bool', 'array', 'anim', 'animator', 'interpolator', 'fraction', 'mipmap', 'plurals', 'raw', 'transition', 'xml'):
    ids = public_ids(kind)
    if not ids: continue
    lines.append('  public static final class %s {' % kind)
    for n, v in sorted(ids.items()): lines.append('    public static final int %s = %d;' % (n, v))
    lines.append('  }')
lines.append('  public static final class styleable {')
for name, names in styleables:
    lines.append('    public static final int[] %s = {%s};' % (name, ', '.join(str(attr_ids.get(n, 0)) for n in names)))
    for i, n in enumerate(names): lines.append('    public static final int %s_%s = %d;' % (name, n, i))
lines.append('  }')
lines.append('}')
dst = os.path.join(ROOT, 'runtime', 'framework', 'com', 'android', 'internal', 'R.java')
if os.environ.get('R_OUT'): dst = os.environ['R_OUT']
os.makedirs(os.path.dirname(dst), exist_ok=True)
open(dst, 'w').write('\n'.join(lines) + '\n')
print('%d styleables, %d attributes (%d public)' % (len(styleables), len(all_attrs), len(attr_ids)))
