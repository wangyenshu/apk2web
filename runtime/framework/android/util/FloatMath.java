package android.util;
public class FloatMath {
  public static float floor(float v) { return (float) Math.floor(v); }
  public static float ceil(float v) { return (float) Math.ceil(v); }
  public static float sin(float v) { return (float) Math.sin(v); }
  public static float cos(float v) { return (float) Math.cos(v); }
  public static float sqrt(float v) { return (float) Math.sqrt(v); }
  public static float exp(float v) { return (float) Math.exp(v); }
  public static float pow(float x, float y) { return (float) Math.pow(x, y); }
  public static float hypot(float x, float y) { return (float) Math.hypot(x, y); }
}
